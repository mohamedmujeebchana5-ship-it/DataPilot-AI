def missing_table(st):
    df = need(st)["work"]
    m = miss_mask(df)
    return pd.DataFrame({
        "Column": df.columns,
        "Position": range(1, df.shape[1] + 1),
        "Missing": m.sum().values,
        "Missing %": (100.0 * m.mean()).round(2).values if len(df) else 0,
        "Non-missing": (~m).sum().values,
        "Data type": [str(t) for t in df.dtypes],
    })

def missing_rows(col, st):
    df = need(st)["work"]
    m = miss_mask(df)
    sel = m[col] if col else m.any(axis=1)
    out = df[sel].copy()
    out.insert(0, "Row #", out.index + 1)
    return out.head(1000)

def dup_view(mode, cols, st):
    df = need(st)["work"]
    cols = list(cols or [])
    if mode == "full":
        out = df[df.duplicated(keep=False)]
    elif mode == "unique":
        out = df.drop_duplicates()
    elif mode == "potential":
        if not cols:
            raise gr.Error("Select at least one column under 'Columns to compare'.")
        out = df[df.duplicated(subset=cols, keep=False)].sort_values(cols)
    else:
        if not cols:
            raise gr.Error("Select a column under 'Columns to compare'.")
        c = cols[0]
        vc = df[c].value_counts(dropna=True)
        vc = vc[vc > 1]
        return pd.DataFrame({
            c: vc.index,
            "Count": vc.values,
            "% of rows": (100.0 * vc.values / len(df)).round(2),
        }).head(500)
    out = out.copy()
    out.insert(0, "Row #", out.index + 1)
    return out.head(1000)

def type_issues(st):
    df, t, k = need(st)["work"], st["typed"], st["kinds"]
    rows = []
    for c in df.columns:
        n = df[c].dropna()
        if n.empty:
            rows.append((c, "All values missing", "Consider removing the column"))
            continue
        if df[c].dtype == object:
            if k[c] == "num":
                rows.append((c, "Numbers stored as text", "Auto-converted in typed layer or use Cleaning tab"))
            if k[c] == "date":
                rows.append((c, "Dates stored as text", "Convert to datetime (Cleaning tab)"))
            if n.map(type).nunique() > 1:
                rows.append((c, "Mixed Python types", "Convert to text or clean values"))
            if k[c] in ("cat",):
                s = n.astype(str)
                canon = s.str.strip().str.lower().str.replace(r"\s+", " ", regex=True)
                if canon.nunique() < s.nunique():
                    rows.append((c, "Inconsistent labels (case/spacing variants)", "Standardize labels (Cleaning tab)"))
        if k[c] == "date" and df[c].dtype == object:
            bad = int(t[c].isna().sum() - miss_mask(df)[c].sum())
            if bad > 0:
                rows.append((c, f"{bad} unparseable date strings", "Inspect rows then fix"))
    return pd.DataFrame(rows, columns=["Column", "Possible issue", "Suggestion"]) if rows else pd.DataFrame({"Result": ["✅ No type issues detected — dataset is clean!"]})

def quality_summary(st):
    df = need(st)["work"]
    m = miss_mask(df)
    rep = int(sum(1 for c in df.columns if df[c].duplicated().any()))
    iss = type_issues(st)
