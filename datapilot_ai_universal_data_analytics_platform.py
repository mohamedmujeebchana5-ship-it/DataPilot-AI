CLEAN_OPS = [
    "Run Full Auto-Clean Pipeline (dedupe, impute missing, fix text & types)",
    "Remove fully duplicated rows",
    "Fill missing numerical values (median)",
    "Fill missing numerical values (mean)",
    "Fill missing numerical values (0)",
    "Fill missing categorical values (most frequent)",
    "Fill missing categorical values ('Unknown')",
    "Remove rows with missing values",
    "Convert column to numeric",
    "Convert column to date",
    "Convert column to text",
    "Rename column (new name below)",
    "Remove column",
    "Standardize labels (trim, lowercase, single spaces)",
]

def clean_result(op, col, new, st):
    df = need(st)["work"].copy()
    col = col or None
    m = miss_mask(df)
    if op.startswith("Run Full Auto-Clean"):
        cleaned_df, _, _ = auto_prep_pipeline(df)
        return cleaned_df
    if op.startswith("Remove fully"):
        return df.drop_duplicates().reset_index(drop=True)
    if op.startswith("Remove rows"):
        return (df[~m.any(axis=1)] if not col else df[~m[col]]).reset_index(drop=True)
    cols_need = ("Convert", "Rename", "Remove column", "Standardize")
    if op.startswith(cols_need) and not col:
        raise gr.Error("Select a target column first.")
    if op.startswith("Fill missing numerical"):
        targets = [col] if col else [c for c in df.columns if st["kinds"][c] == "num"]
        for c in targets:
            s = pd.to_numeric(df[c].astype(str).str.replace(",", "", regex=False).where(~m[c]), errors="coerce")
            if s.notna().sum() == 0:
                continue
            df[c] = s.fillna(s.mean() if "mean" in op else s.median() if "median" in op else 0)
    elif op.startswith("Fill missing categorical"):
        targets = [col] if col else [c for c in df.columns if st["kinds"][c] in ("cat", "text")]
        for c in targets:
            s = df[c].where(~m[c])
            fill = "Unknown" if "Unknown" in op else (s.mode().iloc[0] if s.notna().any() else "Unknown")
            df[c] = s.fillna(fill)
    elif op.startswith("Convert column to numeric"):
        df[col] = pd.to_numeric(df[col].astype(str).str.replace(",", "", regex=False), errors="coerce")
    elif op.startswith("Convert column to date"):
        df[col] = pd.to_datetime(df[col], errors="coerce")
    elif op.startswith("Convert column to text"):
        df[col] = df[col].astype(str).where(df[col].notna())
    elif op.startswith("Rename"):
        if not new or not new.strip():
            raise gr.Error("Type the new column name.")
        if new in df.columns:
            raise gr.Error("A column with that name already exists.")
        df = df.rename(columns={col: new.strip()})
    elif op.startswith("Remove column"):
        df = df.drop(columns=[col])
    elif op.startswith("Standardize"):
        df[col] = df[col].astype(str).str.strip().str.lower().str.replace(r"\s+", " ", regex=True).where(df[col].notna())
    return df

def clean_preview(op, col, new, st):
    r = clean_result(op, col, new, st)
    w = st["work"]
    return f"🔍 **Preview:** `{len(w):,} × {w.shape[1]}` → `{len(r):,} × {r.shape[1]}` (Completeness: `{completeness(r):.1f}%`). Press **Apply** to commit.", r.head(25)

def clean_apply(op, col, new, st):
    r = clean_result(op, col, new, st)
    st["work"] = r
    st = refresh(st)
    return [
        st,
        f"✅ **Applied:** `{op}`. Working dataset is now `{len(r):,} × {r.shape[1]}` (`{completeness(r):.1f}%` complete).",
        overview(st),
        r.head(25),
        st["ready_path"],
    ] + dd(r.columns)

def restore(st):
    need(st)
    st["work"] = st["orig"].copy()
    st = refresh(st)
    return [
        st,
        "↩️ **Restored original raw dataset.**",
        overview(st),
        st["work"].head(25),
        st["ready_path"],
    ] + dd(st["work"].columns)

def export(which, fmt, st):
    need(st)
    base = os.path.join(tempfile.gettempdir(), "datapilot_" + which.split()[0].lower())
    if which.startswith("Analysis"):
        df = pd.concat([profile_table(st).assign(Section="Profile")], ignore_index=True)
    else:
        df = {
            "Original data": st["orig"],
            "Filtered data": st["work"].loc[st["fidx"]],
            "Cleaned / working data": st["work"],
        }[which]
    p = base + (".csv" if fmt == "CSV" else ".xlsx")
    if fmt == "CSV":
        df.to_csv(p, index=False)
    else:
        d2 = df.copy()
        for c in d2.columns:
            if isinstance(d2[c].dtype, pd.DatetimeTZDtype):
                d2[c] = d2[c].dt.tz_localize(None)
        d2.to_excel(p, index=False)
    return p, f"✅ Exported `{len(df):,}` rows × `{df.shape[1]}` columns to **{fmt}**."


