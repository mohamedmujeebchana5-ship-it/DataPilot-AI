def eda(st):
    need(st)
    d = cur(st)
    nums = of_kind(st, "num")
    cats = of_kind(st, "cat", "bool")
    dates = of_kind(st, "date")
    if d.empty:
        raise gr.Error("The filtered dataset has no rows.")

    num_t = pd.DataFrame()
    if nums:
        num_t = d[nums].agg(["count", "mean", "median", "std", "min", "max"]).T
        num_t["Q1"], num_t["Q3"] = d[nums].quantile(0.25), d[nums].quantile(0.75)
        num_t["IQR"] = num_t["Q3"] - num_t["Q1"]
        num_t = num_t.round(3).reset_index().rename(columns={"index": "Column"})

    cat_rows = []
    for c in cats:
        vc = d[c].value_counts()
        cat_rows.append({
            "Column": c,
            "Unique": len(vc),
            "Most frequent": str(vc.index[0]) if len(vc) else "-",
            "Top count": int(vc.iloc[0]) if len(vc) else 0,
            "Top %": round(100.0 * vc.iloc[0] / max(d[c].notna().sum(), 1), 1) if len(vc) else 0,
            "Missing": int(d[c].isna().sum()),
        })

    out_rows = []
    for c in nums:
        s = d[c].dropna()
        if len(s) < 4:
            continue
        q1, q3 = s.quantile(0.25), s.quantile(0.75)
        iqr = q3 - q1
        lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        n_out = int(((s < lo) | (s > hi)).sum())
        out_rows.append({
            "Column": c,
            "Lower bound": round(float(lo), 3),
            "Upper bound": round(float(hi), 3),
            "Potential outliers": n_out,
            "% flagged": round(100.0 * n_out / len(s), 2),
        })

    date_rows = [{
        "Column": c,
        "Earliest": str(d[c].min()),
        "Latest": str(d[c].max()),
        "Span (days)": (d[c].max() - d[c].min()).days if d[c].notna().any() else None,
        "Missing": int(d[c].isna().sum()),
    } for c in dates]

    empty = lambda m: pd.DataFrame({"Info": [m]})
    corr = None
    if len(nums) >= 2:
        corr = style_fig(
            px.imshow(
                d[nums].corr(),
                text_auto=".2f",
                color_continuous_scale="RdBu_r",
                zmin=-1,
                zmax=1,
            ),
            "Correlation Matrix (Numerical Columns)"
        )
    return (
        num_t if nums else empty("No numerical columns"),
        pd.DataFrame(cat_rows) if cat_rows else empty("No categorical columns"),
        pd.DataFrame(out_rows) if out_rows else empty("No outlier analysis possible"),
        pd.DataFrame(date_rows) if date_rows else empty("No date columns"),
        corr,
    )


