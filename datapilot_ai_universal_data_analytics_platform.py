def read_any(path, sheet=None):
    ext = os.path.splitext(path)[1].lower()
    if ext not in (".csv", ".tsv", ".xlsx", ".xls", ".json"):
        raise ValueError(f"Unsupported file type '{ext}'. Use CSV, TSV, XLSX, XLS or JSON.")
    if os.path.getsize(path) > MAX_MB * 1024 * 1024:
        raise ValueError(f"File is larger than {MAX_MB} MB. Split it or load a subset outside this app.")
    if ext == ".csv":
        try:
            return pd.read_csv(path, sep=None, engine="python")
        except UnicodeDecodeError:
            return pd.read_csv(path, sep=None, engine="python", encoding="latin-1")
    if ext == ".tsv":
        return pd.read_csv(path, sep="\t")
    if ext == ".json":
        try:
            return pd.read_json(path)
        except ValueError:
            return pd.read_json(path, lines=True)
    return pd.read_excel(path, sheet_name=sheet or 0)

def dedupe_columns(df):
    seen, new = {}, []
    for c in df.columns:
        c_clean = re.sub(r"\s+", " ", str(c).strip()) or "Unnamed_Col"
        seen[c_clean] = seen.get(c_clean, 0) + 1
        new.append(c_clean if seen[c_clean] == 1 else f"{c_clean}_{seen[c_clean]}")
    renamed = [n for n, o in zip(new, df.columns) if n != str(o)]
    df.columns = new
    return df, renamed

def sheets_url(url):
    m = re.search(r"/d/([a-zA-Z0-9_-]+)", url or "")
    if not m:
        raise ValueError("That does not look like a Google Sheets URL.")
    g = re.search(r"gid=(\d+)", url)
    return f"https://docs.google.com/spreadsheets/d/{m.group(1)}/export?format=csv" + (f"&gid={g.group(1)}" if g else "")

NULL_TOKENS = {"", "nan", "none", "null", "n/a", "na", "-", "--", "?", "nil", "undefined"}

def miss_mask(df):
    m = df.isna().copy()
    for i, c in enumerate(df.columns):
        if df.dtypes.iloc[i] == object:
            m[c] = m[c] | df[c].astype(str).str.strip().str.lower().isin(NULL_TOKENS)
    return m

def col_kind(s, name):
    n = s.dropna()
    if n.empty:
        return "empty"
    if pd.api.types.is_bool_dtype(s):
        return "bool"
    if pd.api.types.is_datetime64_any_dtype(s):
        return "date"
    if pd.api.types.is_numeric_dtype(s):
        return "id" if ID_RE.search(str(name)) and n.nunique() > 0.9 * len(n) else "num"
    t = n.astype(str).str.strip()
    t = t[~t.str.lower().isin(NULL_TOKENS)]
    if t.empty:
        return "empty"
    if t.str.lower().isin(["true", "false", "yes", "no"]).all():
        return "bool"
    cleaned_num = t.str.replace(r"[$€£₹,%]", "", regex=True).str.replace(",", "", regex=False).str.strip()
    if pd.to_numeric(cleaned_num, errors="coerce").notna().mean() >= 0.92:
        return "num"
    if t.str.contains(r"\d").all() and pd.to_datetime(t.head(500), errors="coerce").notna().mean() >= 0.88:
        return "date"
    if ID_RE.search(str(name)) and t.nunique() > 0.9 * len(t):
        return "id"
    return "text" if t.nunique() > 50 and t.nunique() > 0.5 * len(t) else "cat"

def typed_frame(df):
    out, kinds = df.copy(), {}
    for c in df.columns:
        k = col_kind(df[c], c)
        kinds[c] = k
        if df[c].dtype == object:
            t = df[c].astype(str).str.strip()
            t = t.where(~t.str.lower().isin(NULL_TOKENS), np.nan)
            if k in ("num", "id"):
                clean_s = t.str.replace(r"[$€£₹,%]", "", regex=True).str.replace(",", "", regex=False).str.strip()
                if k == "num" or pd.to_numeric(clean_s.dropna(), errors="coerce").notna().all():
                    out[c] = pd.to_numeric(clean_s, errors="coerce")
                else:
                    out[c] = t
            elif k == "date":
                out[c] = pd.to_datetime(t, errors="coerce")
            elif k == "bool":
                out[c] = t.str.lower().map({"true": True, "false": False, "yes": True, "no": False})
            else:
                out[c] = t
    return out, kinds

def completeness(df):
    cells = df.shape[0] * df.shape[1]
    return 100.0 if cells == 0 else 100.0 * (1.0 - miss_mask(df).values.sum() / cells)

def save_ready_excel(df, base_name="datapilot_ready"):
    clean_name = re.sub(r"[^a-zA-Z0-9_-]", "_", os.path.splitext(base_name)[0])
    path = os.path.join(tempfile.gettempdir(), f"{clean_name}_Analysis_Ready.xlsx")
    d2 = df.copy()
    for c in d2.columns:
        if isinstance(d2[c].dtype, pd.DatetimeTZDtype):
            d2[c] = d2[c].dt.tz_localize(None)
    d2.to_excel(path, index=False)
    return path

def auto_prep_pipeline(df):
    """
    Automatically removes unexpected artifacts, drops exact duplicates,
    parses numbers/dates, and imputes missing values so the dataset is immediately ready for analysis.
    """
    out = df.copy()
    logs = []
    init_rows, init_cols = out.shape

    # 1. Strip control characters, currency noise, & standardize null tokens
    obj_cols = out.select_dtypes(include=["object"]).columns
    unexpected_fixed = 0
    for c in obj_cols:
        raw_s = out[c].astype(str)
        cleaned = (
            raw_s.str.replace(r"[\x00-\x1f\x7f-\x9f]", "", regex=True)
            .str.replace(r"\s+", " ", regex=True)
            .str.strip()
        )
        is_null = out[c].isna() | cleaned.str.lower().isin(NULL_TOKENS)
        unexpected_fixed += int((raw_s != cleaned).sum())
        out[c] = cleaned.where(~is_null, np.nan)
    if unexpected_fixed > 0:
        logs.append(f"Sanitized <b>{unexpected_fixed:,}</b> cells containing extra whitespace, hidden characters, or placeholder null strings.")

    # 2. Drop completely empty rows and columns
    empty_cols = [c for c in out.columns if out[c].isna().all()]
    if empty_cols:
        out = out.drop(columns=empty_cols)
        logs.append(f"Removed <b>{len(empty_cols)}</b> completely empty column(s): {', '.join(empty_cols[:5])}.")
    before_empty_rows = len(out)
    out = out.dropna(how="all").reset_index(drop=True)
    if len(out) < before_empty_rows:
        logs.append(f"Removed <b>{before_empty_rows - len(out):,}</b> completely blank row(s).")

    # 3. Drop exact duplicate rows
    dup_count = int(out.duplicated().sum())
    if dup_count > 0:
        out = out.drop_duplicates().reset_index(drop=True)
        logs.append(f"Removed <b>{dup_count:,}</b> exact duplicate row(s).")

    # 4. Type inference & conversion (currency/commas -> numeric, date strings -> datetime)
    typed_df, kinds = typed_frame(out)
    out = typed_df

    # 5. Smart Missing Value Imputation (Median for numeric, Mode/'Unknown' for categorical)
    num_imputed, cat_imputed = 0, 0
    for c in out.columns:
        k = kinds.get(c)
        na_cnt = int(out[c].isna().sum())
        if na_cnt == 0:
            continue
        if k == "num":
            med = out[c].median()
            fill_val = med if pd.notna(med) else 0
            out[c] = out[c].fillna(fill_val)
            num_imputed += na_cnt
        elif k in ("cat", "text"):
            modes = out[c].mode(dropna=True)
            fill_val = modes.iloc[0] if not modes.empty else "Unknown"
            out[c] = out[c].fillna(fill_val)
            cat_imputed += na_cnt
        elif k == "bool":
            modes = out[c].mode(dropna=True)
            fill_val = bool(modes.iloc[0]) if not modes.empty else False
            out[c] = out[c].fillna(fill_val)
            cat_imputed += na_cnt

    if num_imputed > 0:
        logs.append(f"Imputed <b>{num_imputed:,}</b> missing numerical values using column medians.")
    if cat_imputed > 0:
        logs.append(f"Filled <b>{cat_imputed:,}</b> missing categorical/text values using most frequent values.")

    if not logs:
        logs.append("Dataset was already clean! No duplicate rows, missing cells, or formatting anomalies found.")

    summary_html = (
        "<div class='audit-box'><h4>✨ Smart Auto-Prep Pipeline Complete</h4>"
        f"<ul style='margin:0;padding-left:18px'>{''.join(f'<li>{item}</li>' for item in logs)}</ul>"
        f"<div style='margin-top:6px;font-size:12px;color:#a7f3d0'>Shape: {init_rows:,} × {init_cols} → <b>{len(out):,} × {out.shape[1]}</b> | Completeness: <b>{completeness(out):.1f}%</b></div>"
        "</div>"
    )
    return out, logs, summary_html


