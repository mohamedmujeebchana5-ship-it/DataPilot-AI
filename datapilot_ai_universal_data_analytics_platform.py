def apply_one(s, kind, op, v1, v2):
    v1, v2 = (v1 or "").strip(), (v2 or "").strip()
    if op == "is missing":
        return s.isna()
    if op == "not missing":
        return s.notna()
    if kind == "num" or (kind == "id" and pd.api.types.is_numeric_dtype(s)):
        a = float(v1) if v1 else None
        b = float(v2) if v2 else None
        if op == "between":
            return (s >= (a if a is not None else -np.inf)) & (s <= (b if b is not None else np.inf))
        if op == ">=":
            return s >= a
        if op == "<=":
            return s <= a
        if op == "equals":
            return s == a
    elif kind == "date":
        a = pd.to_datetime(v1) if v1 else pd.Timestamp.min
        b = pd.to_datetime(v2) if v2 else pd.Timestamp.max
        if op == "between":
            return (s >= a) & (s <= b)
    elif kind == "bool":
        if op == "equals":
            return s == (v1.lower() == "true")
    else:
        t = s.astype(str).str.lower()
        q = v1.lower()
        if op == "in list":
            return t.isin([x.strip().lower() for x in v1.split(",")]) & s.notna()
        if op == "equals":
            return (t == q) & s.notna()
        if op == "contains":
            return t.str.contains(q, regex=False) & s.notna()
        if op == "starts with":
            return t.str.startswith(q) & s.notna()
        if op == "ends with":
            return t.str.endswith(q) & s.notna()
    raise ValueError(f"Operator '{op}' is not valid for a {kind} column.")

OPS = {
    "num": ["between", ">=", "<=", "equals", "is missing", "not missing"],
    "date": ["between", "is missing", "not missing"],
    "bool": ["equals", "is missing", "not missing"],
}
TXT_OPS = ["in list", "equals", "contains", "starts with", "ends with", "is missing", "not missing"]

def col_changed(col, st):
    if not st or "kinds" not in st or not col:
        return gr.update(), ""
    k = st["kinds"][col]
    s = st["typed"][col]
    if k == "num":
        h = f"Numeric range: `{s.min():g}` to `{s.max():g}`. Use `between` with min and max."
    elif k == "date":
        h = f"Dates: `{s.min()}` to `{s.max()}`. Enter `YYYY-MM-DD`."
    elif k == "bool":
        h = "Enter `True` or `False`."
    elif k == "id":
        h = "Identifier column: use `equals` or `in list` (comma-separated)."
    else:
        top_vals = ", ".join(map(str, s.dropna().astype(str).value_counts().head(10).index))
        h = f"Sample values: {top_vals}" + (" ..." if s.nunique() > 10 else "")
    ops = OPS.get(k, TXT_OPS)
    return gr.update(choices=ops, value=ops[0]), h

def filter_summary(st):
    if not st["filters"]:
        return f"No filters active. Showing all {len(st['typed']):,} rows."
    return (
        "Active filters (all must match):\n"
        + "\n".join(f"- {c} {o} {a} {b}".strip() for c, o, a, b in st["filters"])
        + f"\n\nMatching rows: {len(st['fidx']):,} of {len(st['typed']):,}"
    )

def run_filters(st):
    t = st["typed"]
    mask = pd.Series(True, index=t.index)
    for c, o, a, b in st["filters"]:
        mask &= apply_one(t[c], st["kinds"][c], o, a, b).fillna(False)
    st["fidx"] = t.index[mask]
    return st

def filter_outputs(st):
    d = cur(st)
    num = d[of_kind(st, "num")]
    stats = (
        num.describe().T.round(3).reset_index().rename(columns={"index": "Column"})
        if num.shape[1]
        else pd.DataFrame({"Info": ["No numerical columns"]})
    )
    return st, filter_summary(st), d.head(100), stats

def add_filter(col, op, v1, v2, st):
    need(st)
    if not col or col not in st["typed"].columns:
        raise gr.Error("Choose a column to filter.")
    try:
        apply_one(st["typed"][col].head(5), st["kinds"][col], op, v1, v2)
    except Exception as e:
        raise gr.Error(f"Invalid filter: {e}")
    st["filters"].append((col, op, v1 or "", v2 or ""))
    return filter_outputs(run_filters(st))

def undo_filter(st):
    need(st)
    if st["filters"]:
        st["filters"].pop()
    return filter_outputs(run_filters(st))

def reset_filters(st):
    need(st)
    st["filters"] = []
    return filter_outputs(run_filters(st))


